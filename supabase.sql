-- LINK HUB · historial de salud de aplicaciones
create table if not exists public.link_app_metrics (
  id bigint generated by default as identity primary key,
  app_id text not null,
  is_up boolean not null,
  status_code integer,
  latency_ms integer,
  checked_at timestamptz not null default now(),
  source text not null default 'link-hub'
);

create index if not exists link_app_metrics_app_checked_idx
  on public.link_app_metrics(app_id, checked_at desc);

alter table public.link_app_metrics enable row level security;

-- No se crean políticas para anon/authenticated.
